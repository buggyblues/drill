/** Run against an isolated demo: UI_TEST_URL=http://127.0.0.1:8792.
 * Requires Playwright (UI_PLAYWRIGHT_MODULE may point to a bundled installation).
 * Writes screenshots to UI_REPORT_DIR and creates one test object in the target demo.
 */
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.UI_PLAYWRIGHT_MODULE || 'playwright');
const url = process.env.UI_TEST_URL || 'http://127.0.0.1:8792';
const report = process.env.UI_REPORT_DIR || '/private/tmp/drill-recap-report';
await mkdir(report, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const errors = [], checks = [];
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
const page = await context.newPage();
page.on('pageerror', error => errors.push(error.message));
const record = name => { checks.push(name); console.log('PASS ' + name); };
try {
  await page.goto(url);
  // Refuse to create verification content against a real backend.
  const health = await (await page.request.get(url + '/health')).json();
  assert.equal(health.mode, 'demo', 'UI verification requires an isolated demo backend');
  await page.getByRole('heading', { name: '最近新增', exact: true }).waitFor();
  await page.getByRole('radio', { name: '全部', exact: true }).check();
  const primary = page.locator('.rc-page-actions').getByRole('button', { name: '快速创建', exact: true });
  assert.notEqual(await primary.evaluate(el => getComputedStyle(el).backgroundColor), 'rgba(0, 0, 0, 0)');
  assert.ok(await primary.evaluate(el => el.getBoundingClientRect().height >= 32));
  await page.screenshot({ path: report + '/desktop-light.png' });
  record('desktop renders shared Recap styles');
  await page.getByRole('radio', { name: '卡片', exact: true }).check();
  assert.ok(await page.locator('.drill-object-card').count() > 0);
  await page.getByRole('button', { name: '切换深色主题' }).click();
  assert.equal(await page.locator('.drill-ui').getAttribute('data-theme'), 'dark');
  await page.screenshot({ path: report + '/desktop-dark-cards.png' });
  await page.reload();
  await page.getByRole('heading', { name: '最近新增', exact: true }).waitFor();
  assert.equal(await page.locator('.drill-ui').getAttribute('data-theme'), 'dark');
  record('card view and persisted dark theme');
  const nav = page.locator('.app-shell > .sidebar');
  await nav.getByRole('button', { name: '项目', exact: true }).click();
  await page.getByRole('heading', { name: '项目', exact: true }).waitFor();
  await page.getByRole('button', { name: '新建项目', exact: true }).click();
  const createProject = page.getByRole('dialog', { name: '新建项目', exact: true });
  const projectTitle = 'Recap UI 验收 项目 ' + Date.now();
  await createProject.getByRole('textbox', { name: '新建项目' }).fill(projectTitle);
  await createProject.getByRole('button', { name: '保存', exact: true }).click();
  await createProject.waitFor({ state: 'hidden' });
  await page.locator('.object-title').filter({ hasText: projectTitle }).waitFor();
  await page.getByRole('button', { name: '对象归属', exact: true }).click();
  const options = page.locator('.property-options');
  const choices = options.getByRole('checkbox');
  assert.ok(await choices.count() >= 2);
  for (const index of [0, 1]) {
    const pushed = page.waitForResponse(response => response.url().endsWith('/sync/push') && response.request().method() === 'POST');
    await choices.nth(index).check();
    assert.ok((await pushed).ok());
  }
  await options.getByRole('button', { name: '完成', exact: true }).click();
  const projectSnap = await (await page.request.get(url + '/bootstrap')).json();
  const project = projectSnap.objects.find(o => o.title === projectTitle);
  assert.equal(projectSnap.relations.filter(r => r.from_id === project.id && r.type === 'belongs' && !r.deleted_at).length, 2);
  await page.request.post(url + '/sync/push', { data: { device_id: 'recap-ui-verification', changes: [{ mutation_id: crypto.randomUUID(), object_id: project.id, field: 'deleted_at', value: Date.now(), base_rev: project.rev, client_ts: Date.now() }] } });
  record('project creation and multiple domain assignments persist');
  await nav.getByRole('button', { name: '领域', exact: true }).click();
  await page.getByRole('heading', { name: '领域', exact: true }).waitFor();
  await nav.getByRole('button', { name: '行动', exact: false }).click();
  await page.getByRole('radio', { name: '看板', exact: true }).check();
  assert.equal(await page.locator('.board-column').count(), 4);
  record('domain/project navigation and action board');
  await page.getByRole('button', { name: '全局搜索', exact: true }).click();
  const search = page.getByRole('dialog', { name: '搜索与命令' });
  await search.getByRole('combobox').fill('喜欢');
  await search.getByRole('option').first().waitFor();
  await search.getByRole('combobox').press('Enter');
  await page.locator('.object-title').filter({ hasText: '喜欢的工具应该安静一点' }).waitFor();
  record('server search opens an object with Enter');
  await page.getByRole('button', { name: '全局搜索', exact: true }).click();
  await search.getByRole('combobox').fill('>设置');
  await search.getByRole('combobox').press('Enter');
  await page.getByRole('heading', { name: '偏好与连接', exact: true }).waitFor();
  await page.getByRole('radio', { name: '紧凑', exact: true }).check();
  assert.equal(await page.locator('.drill-ui').getAttribute('data-density'), 'compact');
  record('command keyboard selection and density settings');
  await nav.getByRole('button', { name: '最近新增', exact: true }).click();
  await primary.click();
  const capture = page.getByRole('dialog', { name: '快速创建' });
  await capture.getByRole('textbox', { name: '捕获内容' }).fill('Recap UI 验收 ' + Date.now());
  const text = await capture.getByRole('textbox').inputValue();
  let commits = 0;
  await page.route('**/sync/push', async route => { commits++; await new Promise(resolve => setTimeout(resolve, 300)); await route.continue(); });
  await capture.getByRole('button', { name: '保存', exact: true }).click();
  await page.keyboard.press('Enter');
  await page.locator('.object-title').filter({ hasText: text }).waitFor();
  assert.equal(commits, 1);
  assert.equal(await capture.getByRole('textbox').inputValue(), '');
  await capture.getByRole('button', { name: '关闭', exact: true }).click();
  await page.reload();
  await page.getByRole('heading', { name: '最近新增', exact: true }).waitFor();
  const snap = await (await page.request.get(url + '/bootstrap')).json();
  assert.equal(snap.objects.filter(o => o.title === text).length, 1);
  const created = snap.objects.find(o => o.title === text);
  await page.request.post(url + '/sync/push', { data: { device_id: 'recap-ui-verification', changes: [{ mutation_id: crypto.randomUUID(), object_id: created.id, field: 'deleted_at', value: Date.now(), base_rev: created.rev, client_ts: Date.now() }] } });
  record('quick capture saves once, clears input, survives reload');
  const property = page.getByRole('combobox', { name: '对象类型', exact: true });
  await property.click();
  await page.getByRole('option', { name: '行动', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  await page.locator('.rc-menu-popup').waitFor({ state: 'hidden' });
  record('property selector portal and Escape dismissal');
  await nav.getByRole('button', { name: '画布', exact: true }).click();
  await page.locator('.canvas-tile').first().dblclick();
  await page.locator('.canvas-stage').waitFor();
  record('existing canvas still opens');
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
  mobile.on('pageerror', error => errors.push(error.message));
  await mobile.goto(url);
  await mobile.getByRole('heading', { name: '最近新增', exact: true }).waitFor();
  assert.equal(await mobile.locator('.right-pane').count(), 0);
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await mobile.getByRole('button', { name: '打开导航', exact: true }).click();
  const sheet = mobile.getByRole('dialog', { name: '导航', exact: true });
  await sheet.getByRole('button', { name: '项目', exact: true }).click();
  await mobile.getByRole('heading', { name: '项目', exact: true }).waitFor();
  await sheet.waitFor({ state: 'hidden' });
  assert.notEqual(await mobile.locator('.mobile-capture').evaluate(el => getComputedStyle(el).color), await mobile.locator('.mobile-capture').evaluate(el => getComputedStyle(el).backgroundColor));
  await mobile.screenshot({ path: report + '/mobile-projects.png' });
  const row = mobile.getByRole('option').first();
  await row.click();
  await mobile.locator('.right-pane').waitFor();
  await mobile.getByRole('button', { name: '折叠上下文栏' }).click();
  assert.equal(await mobile.locator('.right-pane').count(), 0);
  record('mobile navigation, object details and no horizontal overflow');
  assert.deepEqual(errors, []);
  await writeFile(report + '/results.json', JSON.stringify({ checks, errors, passed: true }, null, 2));
} catch (error) { await page.screenshot({ path: report + '/failure.png' }); console.log((await page.locator('body').innerText()).slice(-2500)); throw error; } finally { await browser.close(); }
